<h1>mudui</h1>
<p>
	A terminal renderer and UI kit for Svelte 5, built on Svelte's custom renderer API. Its
	components render to the terminal, not the DOM, so there's nothing to preview here.
</p>
<p>Try the example app instead:</p>
<pre>bun run example</pre>
<p>See <code>README.md</code> for documentation.</p>
